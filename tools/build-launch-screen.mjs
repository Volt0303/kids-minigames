#!/usr/bin/env node
/**
 * Android launch screen for the game being built (VITE_GAME), drawn to look exactly like the
 * web loading screen in index.html, so the app shows one loading screen from the moment it is
 * tapped — not Android's default splash, then a white web view, then the web loading screen.
 *
 *   android/app/src/main/res/drawable-nodpi/launch_backdrop.jpg  the game's backdrop with the same
 *                                                                light wash as the web page (plain
 *                                                                light blue for games without one)
 *   android/app/src/main/res/drawable-nodpi/launch_guide.png     the guide character, or the plain
 *                                                                circle for games that must not show it
 *   android/app/src/main/res/values/launch_screen.xml            its size on screen and the Android 12
 *                                                                system-splash colour
 *
 * res/drawable/launch_screen.xml (committed) puts them together. These files are generated and
 * git-ignored; `npm run assets` (part of every build) writes them.
 *
 * Usage: VITE_GAME=<id> node tools/build-launch-screen.mjs
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import sharp from 'sharp';
import { gameArtUrl, hasGameArt, LOADING_GUIDE_URL } from '../src/core/assets/catalog.ts';
import { GAME_HAS_GUIDE, isGameId } from '../src/games/registry.ts';

const RES = 'android/app/src/main/res';
/** Same values as the web loading screen (index.html). */
const PAGE_COLOR = '#dcf2ff';
const WASH_OPACITY = 0.35;
const AVATAR_BOX_DP = 170;
const CIRCLE_COLOR = '#2b7de9';
/** Launch pictures are only shown for a moment; this keeps the APK small. */
const BACKDROP_WIDTH = 1280;

const game = process.env.VITE_GAME;
const gameId = isGameId(game) ? game : undefined;
const withGuide = gameId !== undefined && GAME_HAS_GUIDE[gameId];
const withBackdrop = hasGameArt(gameId, 'backdrop');

async function writeBackdrop(target) {
  if (!withBackdrop) {
    await sharp({ create: { width: 8, height: 8, channels: 3, background: PAGE_COLOR } })
      .jpeg()
      .toFile(target);
    return PAGE_COLOR;
  }
  const source = `public/${gameArtUrl(gameId, 'backdrop')}`;
  if (!existsSync(source)) throw new Error(`${source} is missing — run build-images first`);
  const base = sharp(source).resize({ width: BACKDROP_WIDTH });
  const { info } = await base.clone().toBuffer({ resolveWithObject: true });
  const { width, height } = info;
  const wash = await sharp({
    create: { width, height, channels: 4, background: { r: 220, g: 242, b: 255, alpha: WASH_OPACITY } },
  })
    .png()
    .toBuffer();
  const washed = await base
    .composite([{ input: wash }])
    .jpeg({ quality: 82, mozjpeg: true })
    .toBuffer();
  writeFileSync(target, washed);
  const { dominant } = await sharp(washed).stats();
  return `#${[dominant.r, dominant.g, dominant.b].map((v) => v.toString(16).padStart(2, '0')).join('')}`;
}

/** The character fitted into the web page's 170 × 170 box (background-size: contain). */
async function writeGuide(target) {
  if (!withGuide) {
    const size = 340;
    const circle = `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}"><circle cx="${size / 2}" cy="${size / 2}" r="${size / 2}" fill="${CIRCLE_COLOR}"/></svg>`;
    await sharp(Buffer.from(circle)).png().toFile(target);
    return { width: AVATAR_BOX_DP, height: AVATAR_BOX_DP };
  }
  const source = `public/${LOADING_GUIDE_URL}`;
  if (!existsSync(source)) throw new Error(`${source} is missing — run build-images first`);
  // 3× the on-screen size: sharp on high-density tablets without bloating the APK.
  const info = await sharp(source)
    .resize({ height: AVATAR_BOX_DP * 3 })
    .png()
    .toFile(target);
  const scale = AVATAR_BOX_DP / Math.max(info.width, info.height);
  return { width: Math.round(info.width * scale), height: Math.round(info.height * scale) };
}

async function main() {
  mkdirSync(`${RES}/drawable-nodpi`, { recursive: true });
  const splashColor = await writeBackdrop(`${RES}/drawable-nodpi/launch_backdrop.jpg`);
  const guide = await writeGuide(`${RES}/drawable-nodpi/launch_guide.png`);
  writeFileSync(
    `${RES}/values/launch_screen.xml`,
    `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/build-launch-screen.mjs for "${gameId ?? 'demo'}" — do not edit. -->
<resources>
    <dimen name="launch_guide_width">${guide.width}dp</dimen>
    <dimen name="launch_guide_height">${guide.height}dp</dimen>
    <color name="launch_splash_color">${splashColor}</color>
</resources>
`,
  );
  console.log(
    `launch screen ${(gameId ?? 'demo').padEnd(10)} ${withGuide ? 'character' : 'circle'}, ${withBackdrop ? 'backdrop' : 'plain'}`,
  );
}

main().catch((error) => {
  console.error(`build-launch-screen: ${error instanceof Error ? error.message : String(error)}`);
  process.exit(1);
});
